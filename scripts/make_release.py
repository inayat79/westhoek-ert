"""
make_release.py — assemble the v1.0 release bundle (NOT tracked in git; nothing is uploaded).

    conda run -n pg python make_release.py [--tag v1.0-analysis]

Builds <project>/release/westhoek_ert_<tag>/ with
    figures/paper/        paper figures (PDF + 300 dpi PNG)
    results/paper/        tables, numbers.md/json, numbers_diff.md, rebuild_check.md, provenance_audit.md
    environment.yml       conda environment (conda env export --no-builds)
    REFERENCE.md          reference model, settings and decision log
    README.md             contents and rebuild commands
    MANIFEST.sha256       SHA-256 of every file in the bundle
and zips it to <project>/release/westhoek_ert_<tag>.zip, ready for a later Zenodo upload.
"""

import argparse
import datetime as dt
import hashlib
import os
import shutil
import subprocess
import zipfile

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(SCRIPT_DIR, ".."))


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return ""


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


README = """# Westhoek land ERT — probabilistic lens-base and salinity analysis ({tag})

Frozen analysis products of the Westhoek (De Panne, Belgium) land ERT profile: reference inversion, linearised and
Bayesian-evidential-learning (BEL) uncertainty quantification of the saltwater-lens base, and Archie-based salinity
sections.

- Version: `{tag}` — git commit `{commit}`{dirty}
- Bundle assembled: {date}
- Contents: `figures/paper/` (F1–F8 + appendix A1; PDF vector + 300 dpi PNG), `results/paper/` (tables T1–T3 + TA1,
  `numbers.md` = every number quoted in the paper with the script and cached input it comes from, `numbers_diff.md`,
  `rebuild_check.md`, `provenance_audit.md`), `environment.yml`, `REFERENCE.md` (settings and decision log),
  `MANIFEST.sha256`.

## Rebuild

The code lives in the project repository (tag `{tag}`); the raw data are the Westhoek land ERT files
(`land_data.dat`, `elec.dat`, `GPS_coordinate.xlsx`; see `data/raw/Read_me.txt` in the repository).

```
conda env create -f environment.yml          # creates the environment "pg" (pyGIMLi 1.5.5, Python 3.11)
cd scripts
conda run -n pg python run_all.py --from-cache --out ../rebuild     # ~16 min: figures, tables, numbers from the
                                                                     # stored forward runs / samples / inversions,
                                                                     # then --check and --audit against the stored products
conda run -n pg python run_all.py --from-raw --out ../fresh          # lists every step from data/raw with its runtime
conda run -n pg python run_all.py --from-raw --out ../fresh --execute   # ~33 h: rerun everything from data/raw
```

`--from-cache` needs the processed cache (`data/processed/`, ~1.3 GB: inversions, synthetic benchmark runs, BEL prior
samples), which is not part of this bundle. The check compares every rebuilt number with `results/paper/numbers.json`
and cross-checks the numbers that were reported earlier against their original reports; the audit verifies that every
file read by the rebuild is produced by a `--from-raw` step.

## Seeds

All random seeds are listed in the script docstrings (`scripts/1*_*.py`) and in `REFERENCE.md`.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="v1.0-analysis")
    a = ap.parse_args()
    rel_root = os.path.join(ROOT, "release")
    name = f"westhoek_ert_{a.tag}"
    out = os.path.join(rel_root, name)
    if os.path.exists(out):
        shutil.rmtree(out)                                   # the bundle folder is generated by this script only
    os.makedirs(out)
    shutil.copytree(os.path.join(ROOT, "figures", "paper"), os.path.join(out, "figures", "paper"))
    shutil.copytree(os.path.join(ROOT, "results", "paper"), os.path.join(out, "results", "paper"))
    shutil.copy2(os.path.join(ROOT, "environment.yml"), out)
    shutil.copy2(os.path.join(ROOT, "results", "REFERENCE.md"), out)
    dirty = git("status", "--porcelain", "--untracked-files=no")
    with open(os.path.join(out, "README.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(README.format(tag=a.tag, commit=git("rev-parse", "HEAD") or "unknown",
                              dirty=" (working tree had uncommitted changes)" if dirty else "",
                              date=dt.date.today().isoformat()))
    files = sorted(os.path.relpath(os.path.join(d, fn), out).replace("\\", "/")
                   for d, _, fns in os.walk(out) for fn in fns)
    with open(os.path.join(out, "MANIFEST.sha256"), "w", encoding="utf-8", newline="\n") as f:
        f.writelines(f"{sha256(os.path.join(out, p))}  {p}\n" for p in files)
    zp = os.path.join(rel_root, f"{name}.zip")
    if os.path.exists(zp):
        os.remove(zp)
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for p in files + ["MANIFEST.sha256"]:
            z.write(os.path.join(out, p), f"{name}/{p}")
    print(f"[release] {len(files) + 1} files → {zp} ({os.path.getsize(zp) / 1e6:.1f} MB); sha256 {sha256(zp)}")


if __name__ == "__main__":
    main()
